const round = (v: number) => Math.round(v * 1e6) / 1e6;

describe('golden: the rental model must not move', () => {
  for (const scenario of SCENARIOS) {
    it(scenario.name, () => {
      const expected = GOLDEN[scenario.name];
      expect(expected, 'no golden values captured for this scenario').toBeDefined();

      const globals = { ...DEFAULT_GLOBAL_PARAMETERS, ...scenario.globals } as GlobalParameters;
      const result = analyzeStoredHouse(
        {
          price: scenario.price as string,
          hoa: scenario.hoa ?? undefined,
          localParams: {
            mode: null,
            percentDown: scenario.overrides.percentDown ?? null,
            interestRate: scenario.overrides.interestRate ?? null,
            price: scenario.overrides.price ?? null,
            sliderValue: scenario.overrides.monthlyRent ?? 0,
            additionalCashInvestment: scenario.overrides.additionalCashInvestment ?? 0,
            propertyTaxRate: scenario.overrides.propertyTaxRate ?? null,
            vacancyRate: scenario.overrides.vacancyRate ?? null,
            maintenanceRate: scenario.overrides.maintenanceRate ?? null,
            capExRate: scenario.overrides.capExRate ?? null,
            managementRate: scenario.overrides.managementRate ?? null,
            insuranceRate: scenario.overrides.insuranceRate ?? null
          }
        },
        globals
      );

      if ('error' in expected) {
        expect(result.ok).toBe(false);
        if (!result.ok) expect(result.reason).toBe(expected.error);
        return;
      }

      expect(result.ok, 'expected this scenario to analyse').toBe(true);
      if (!result.ok) return;

      // Deliberately shape-agnostic, which is what lets this exact file pass both before and
      // after the result becomes a discriminated union -- an invariant that had to be edited
      // to keep passing would not be one.
      const analysis = result.analysis as Record<string, unknown>;
      const actual = ('detail' in analysis ? analysis.detail : analysis) as Record<string, number | null>;
      for (const [field, want] of Object.entries(expected)) {
        const got = actual[field];
        if (want === null) {
          expect(got, field).toBeNull();
        } else {
          expect(round(got as number), field).toBe(want);
        }
      }
    });
  }
});
